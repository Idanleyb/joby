-- Same spelling rules as the stored names: "קרית" → "קריית", no spaces around "-".
create or replace function public.city_norm(p text)
returns text language sql immutable set search_path = '' as $$
  select nullif(regexp_replace(regexp_replace(replace(trim(coalesce(p, '')), 'קרית ', 'קריית '),
                                              '\s*-\s*', '-', 'g'), '\s+', ' ', 'g'), '')
$$;

create or replace function private.city_point(p text, out lat double precision, out lng double precision)
language sql stable security definer set search_path = '' as $$
  select c.lat, c.lng from public.il_cities c
   where c.name_he = public.city_norm(p) or c.name_he like public.city_norm(p) || '-%'
   order by c.name_he = public.city_norm(p) desc, c.name_he
   limit 1
$$;

-- Straight-line km between two town centres; null when a town is unknown.
create or replace function public.distance_km(a text, b text)
returns numeric language plpgsql stable security definer set search_path = '' as $$
declare p1 record; p2 record;
begin
  if public.city_norm(a) is null or public.city_norm(b) is null then return null; end if;
  if public.city_norm(a) = public.city_norm(b) then return 0; end if;
  select * into p1 from private.city_point(a);
  select * into p2 from private.city_point(b);
  if p1.lat is null or p2.lat is null then return null; end if;
  return round((6371 * 2 * asin(sqrt(
           power(sin(radians(p2.lat - p1.lat) / 2), 2)
         + cos(radians(p1.lat)) * cos(radians(p2.lat)) * power(sin(radians(p2.lng - p1.lng) / 2), 2))))::numeric, 1);
end $$;

