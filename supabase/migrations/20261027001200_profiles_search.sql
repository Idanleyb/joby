-- Job alert to matching providers when a job opens (new, or released by an admin).
create or replace function private.job_alerts()
returns trigger language plpgsql security definer set search_path = '' as $$
declare r record;
begin
  if new.status = 'open' and (tg_op = 'INSERT' or old.status is distinct from 'open') then
    for r in select p.user_id from public.provider_profiles p join public.profiles u on u.id = p.user_id
              where p.verification_status = 'approved' and u.status = 'active'
                and p.user_id is distinct from new.poster_id
                and coalesce(u.notification_prefs ->> 'job_alerts', 'instant') <> 'off'
                and (new.poster_id is null or not public.is_blocked_between(p.user_id, new.poster_id))
                and private.job_matches_provider(new, p.user_id) loop
      perform private.notify(r.user_id, 'job_alert', jsonb_build_object('job_id', new.id, 'title', new.title));
    end loop;
  end if;
  return null;
end $$;
create trigger jobs_alerts after insert or update of status on public.jobs
  for each row execute function private.job_alerts();

-- "Your application was viewed" (PRD 5.10).
create or replace function public.mark_application_viewed(p_app uuid)
returns void language plpgsql security definer set search_path = '' as $$
declare a public.applications := private.require_job_owner_for_app(p_app);
begin
  if a.viewed_at is null and a.credited_back_at is null then
    update public.applications
       set viewed_at = now(), status = case when status = 'sent' then 'viewed' else status end
     where id = a.id;
    perform private.notify(a.provider_id, 'application_viewed', jsonb_build_object('job_id', a.job_id, 'application_id', a.id));
  end if;
end $$;

