-- ---------------------------------------------------------------------------
-- Matching (replaces the region table in the app)
-- ---------------------------------------------------------------------------
create or replace function private.job_matches_provider(p_job public.jobs, p_provider uuid)
returns boolean language plpgsql stable security definer set search_path = '' as $$
declare p public.provider_profiles; d numeric;
begin
  select * into p from public.provider_profiles where user_id = p_provider;
  if p.user_id is null then return false; end if;
  if not exists (select 1 from public.provider_subcategories
                  where provider_id = p_provider and subcategory_id = p_job.subcategory_id) then
    return false;
  end if;
  if p_job.mode <> 'onsite' and p.works_remote then return true; end if;
  if p_job.mode = 'remote' or not p.works_onsite then return false; end if;
  if p.radius_km is null then return true; end if;                 -- nationwide
  d := public.distance_km(p_job.city, p.city);
  if d is null then return public.city_norm(p_job.city) = public.city_norm(p.city); end if;
  return d <= p.radius_km;
end $$;

-- Open jobs that match the signed-in provider (Opportunities → "Matches").
create or replace function public.my_matching_jobs()
returns setof uuid language sql stable security definer set search_path = '' as $$
  select j.id from public.jobs j
   where j.status = 'open' and j.expires_at > now()
     and j.poster_id is distinct from auth.uid()
     and private.job_matches_provider(j, auth.uid())
$$;

-- Open on-site / hybrid jobs within p_radius km of a town (area filter).
create or replace function public.jobs_near(p_city text, p_radius integer default 25)
returns setof uuid language sql stable security definer set search_path = '' as $$
  select j.id from public.jobs j
   where j.status = 'open' and j.expires_at > now() and j.mode <> 'remote'
     and coalesce(public.distance_km(j.city, p_city), case when public.city_norm(j.city) = public.city_norm(p_city) then 0 end)
         <= greatest(coalesce(p_radius, 25), 0)
$$;

-- ---------------------------------------------------------------------------
-- Provider search (Find providers)
-- ---------------------------------------------------------------------------
create or replace function public.search_providers(p_category smallint default null, p_subcategory smallint default null,
                                                   p_city text default null, p_radius integer default null,
                                                   p_available_only boolean default false, p_sort text default 'rating',
                                                   p_limit integer default 100)
returns table (user_id uuid, distance_km numeric, min_price integer)
language sql stable security definer set search_path = '' as $$
  with base as (
    select p.user_id, p.display_name, p.rating_avg, p.rating_count,
           case when p_city is not null then public.distance_km(p.city, p_city) end as dist,
           (select min(s.price_from) from public.service_cards s where s.provider_id = p.user_id) as min_price,
           p.works_remote
      from public.provider_profiles p
     where p.verification_status = 'approved'
       and (not p_available_only or p.availability = 'available' or p.busy_until < current_date)
       and (p_subcategory is null or exists (select 1 from public.provider_subcategories ps
                                              where ps.provider_id = p.user_id and ps.subcategory_id = p_subcategory))
       and (p_category is null or exists (select 1 from public.provider_subcategories ps
                                           join public.subcategories s on s.id = ps.subcategory_id
                                          where ps.provider_id = p.user_id and s.category_id = p_category))
       and (auth.uid() is null or not public.is_blocked_between(auth.uid(), p.user_id))
  )
  select b.user_id, b.dist, b.min_price from base b
   where p_city is null or p_radius is null or b.dist <= p_radius
   order by
     case when p_sort = 'name' then b.display_name end asc,
     case when p_sort = 'price' then b.min_price end asc nulls last,
     case when p_sort = 'distance' then b.dist end asc nulls last,
     case when p_sort = 'rating' and b.rating_count >= 3 then b.rating_avg end desc nulls last,
     b.rating_count desc, b.display_name
   limit least(coalesce(p_limit, 100), 200)
$$;

